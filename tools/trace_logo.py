"""Trace the flat CoolFly logo PNG into polygon paths (black + orange layers).

Output: film/assets/brand/coolfly-logo.svg and film/src/logo-data.js
(polygons normalised to the logo's bounding box, used for the line-assembly finale).
"""
import json, sys
import cv2
import numpy as np

src = sys.argv[1] if len(sys.argv) > 1 else 'film/assets/brand/coolfly-logo.png'
img = cv2.imread(src, cv2.IMREAD_COLOR).astype(np.int32)
b, g, r = img[..., 0], img[..., 1], img[..., 2]
dark = ((r + g + b) < 300).astype(np.uint8) * 255
orange = ((r > 180) & (g > 40) & (g < 150) & (b < 80)).astype(np.uint8) * 255

layers = {}
allpts = []
for name, mask in (('dark', dark), ('orange', orange)):
    contours, hier = cv2.findContours(mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
    polys = []
    for c in contours:
        if cv2.contourArea(c) < 80:
            continue
        a = cv2.approxPolyDP(c, 1.6, True).reshape(-1, 2).tolist()
        polys.append(a)
        allpts += a
    layers[name] = polys

pts = np.array(allpts)
x0, y0 = pts.min(0)
x1, y1 = pts.max(0)
w, h = x1 - x0, y1 - y0
norm = {k: [[[round((x - x0) / w, 5), round((y - y0) / w, 5)] for x, y in p] for p in v] for k, v in layers.items()}

def d(polys):
    return ' '.join('M' + ' L'.join(f'{x - x0},{y - y0}' for x, y in p) + 'Z' for p in polys)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">
  <path fill="#000" fill-rule="evenodd" d="{d(layers['dark'])}"/>
  <path fill="#FF5A00" fill-rule="evenodd" d="{d(layers['orange'])}"/>
</svg>
'''
open('film/assets/brand/coolfly-logo.svg', 'w').write(svg)
open('film/src/logo-data.js', 'w').write(
    '// Auto-generated by tools/trace_logo.py from assets/brand/coolfly-logo.png\n'
    f'// Polygons normalised by logo width; aspect h/w = {h / w:.5f}\n'
    f'export const LOGO = {json.dumps({"aspect": round(h / w, 5), **norm}, separators=(",", ":"))};\n')
print('dark', len(layers['dark']), 'orange', len(layers['orange']), 'size', w, h,
      'pts', sum(len(p) for v in layers.values() for p in v))
